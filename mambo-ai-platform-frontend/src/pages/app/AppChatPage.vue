  messages.value[aiMessageIndex].loading = false
  messages.value[aiMessageIndex].status = 'error'
  
  // 重置生成状态
  generationStatus.value = {
    stage: '生成失败',
    progress: 0,
    isActive: false
  }
  
  message.error('生成失败，请重试')
  isGenerating.value = false
}

